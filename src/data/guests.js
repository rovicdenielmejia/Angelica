export const searchGuests = (query) => {
  if (!query || query.trim() === '') return []
  const searchTerm = query.toLowerCase().trim()
  const getMatchPriority = (name) => {
    const normalizedName = name.toLowerCase()

    if (normalizedName === searchTerm) return 0
    if (normalizedName.startsWith(searchTerm)) return 1
    if (normalizedName.split(' ').some(word => word.startsWith(searchTerm))) return 2
    if (normalizedName.includes(searchTerm)) return 3
    return 4
  }

  return guests
    .filter(guest => guest.name.toLowerCase().includes(searchTerm))
    .sort((a, b) => {
      const priorityA = getMatchPriority(a.name)
      const priorityB = getMatchPriority(b.name)

      if (priorityA !== priorityB) return priorityA - priorityB
      return a.name.localeCompare(b.name)
    })
}
